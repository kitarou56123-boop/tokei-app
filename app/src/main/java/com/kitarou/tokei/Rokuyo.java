    static String name(LocalDate d) {
        long e = d.toEpochDay();
        if (e < START[0] || e >= START[START.length - 1] + 30) return null;
        int lo = 0, hi = START.length - 1;
        while (lo < hi) {
            int mid = (lo + hi + 1) / 2;
            if (START[mid] <= e) lo = mid;
            else hi = mid - 1;
        }
        int day = (int) (e - START[lo]) + 1;
        return NAMES[(MONTH[lo] + day) % 6];
    }
